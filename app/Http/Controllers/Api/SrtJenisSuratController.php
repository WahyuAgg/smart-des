    public function update(UpdateSrtJenisSuratRequest $request, string $id): JsonResponse
    {
        $record = SrtJenisSurat::findOrFail($id);

        try {
            DB::transaction(function () use ($request, $record) {
                $data = $request->only([
                    'kategori_surat_id',
                    'kode_jenis_surat',
                    'nama_jenis_surat',
                    'deskripsi',
                    'is_active',
                ]);

                // Handle template file upload — delete old files if exists
                if ($request->hasFile('template')) {
                    // Delete old docx template
                    if ($record->template_path && Storage::disk('public')->exists($record->template_path)) {
                        Storage::disk('public')->delete($record->template_path);
                    }
                    // Delete old pdf template
                    if ($record->template_pdf_path && Storage::disk('public')->exists($record->template_pdf_path)) {
                        Storage::disk('public')->delete($record->template_pdf_path);
                    }

                    // Store the new docx template
                    $data['template_path'] = $request->file('template')
                        ->store('templates', 'public');

                    // Convert docx to PDF using LibreOffice
                    $fullDocxPath = Storage::disk('public')->path($data['template_path']);
                    $pdfDir = 'templates_pdf';
                    File::ensureDirectoryExists(Storage::disk('public')->path($pdfDir));

                    $converter = new DocumentConverter();
                    $pdfFullPath = $converter->docxToPdf($fullDocxPath);

                    // Move/copy the generated PDF to the public storage templates_pdf directory
                    $pdfFilename = pathinfo($data['template_path'], PATHINFO_FILENAME) . '.pdf';
                    $pdfStoragePath = $pdfDir . '/' . $pdfFilename;

                    if (file_exists($pdfFullPath)) {
                        Storage::disk('public')->put($pdfStoragePath, file_get_contents($pdfFullPath));
                        $data['template_pdf_path'] = $pdfStoragePath;
                        // Clean up the temp PDF generated by LibreOffice
                        @unlink($pdfFullPath);
                    }
                }

                $record->update($data);

                // Sync SrtJenisSuratPenduduk records: delete all, then re-create
                if ($request->has('penduduk_fields')) {
                    $record->srtJenisSuratPenduduks()->delete();

                    $pendudukFields = $request->input('penduduk_fields', []);
                    foreach ($pendudukFields as $field) {
                        $record->srtJenisSuratPenduduks()->create([
                            'urutan' => $field['urutan'],
                            'kode' => $field['kode'],
                            'label' => $field['label'],
                            'deskripsi' => $field['deskripsi'] ?? null,
                            'wajib' => $field['wajib'] ?? true,
                        ]);
                    }
                }
            });

            return $this->success(
                $record->fresh()->load(['srtKategoriSurat', 'srtJenisSuratPenduduks']),
                'Jenis surat berhasil diperbarui.'
            );
        } catch (\Throwable $e) {
            return $this->error(
                'Gagal memperbarui jenis surat: ' . $e->getMessage(),
                null,
                500
            );
        }
    }

    public function destroy(string $id): JsonResponse
    {
        $record = SrtJenisSurat::with('srtJenisSuratPenduduks')->findOrFail($id);

        try {
            DB::transaction(function () use ($record) {
                // Delete template files if exists
                if ($record->template_path && Storage::disk('public')->exists($record->template_path)) {
                    Storage::disk('public')->delete($record->template_path);
                }
                if ($record->template_pdf_path && Storage::disk('public')->exists($record->template_pdf_path)) {
                    Storage::disk('public')->delete($record->template_pdf_path);
                }

                // Delete related penduduk fields
                $record->srtJenisSuratPenduduks()->delete();

                // Delete the record itself
                $record->delete();
            });

            return $this->success(
                null,
                'Jenis surat berhasil dihapus.'
            );
        } catch (\Throwable $e) {
            return $this->error(
                'Gagal menghapus jenis surat: ' . $e->getMessage(),
                null,
                500
            );
        }
    }
}
